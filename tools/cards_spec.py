"""Свои названия, тексты и способности всех карт. Числа - из оригинала (import_cards.py).

Язык способностей (см. js/effects.js):
  P(effect, target, amount, **)  - при розыгрыше (onPlay)
  A(effect, target, amount, cost={...}, **) - активируемая: cost rest/ether/life/sacrifice/sacrificeSelf/once/notInBlock
  ST(scope, **)                  - постоянное свойство: atk, hp, keywords, filter, флаги
  T(trigger, effect, target, amount, **) - срабатывание по событию
  todo(text)                     - ещё не реализовано: карта получает impl: false
Цели с выбором: creature, enemyCreature, friendlyCreature, creatureOrHero, hero, enchantment,
  graveCreature (свой могильник), anyGraveCreature, attackingCreature. "chosen" - цель карты.
Групповые: allCreatures, allEnemyCreatures, allFriendlyCreatures, ownHero, enemyHero, bothHeroes, self,
  enchanted, enchantedController, activeHero.
Количества: число, 'X', 'power' (сила источника), {'count': ..., 'mult': n}, 'sacPower', 'sacToughness' ...
"""

R = {'rest': True}


def P(effect, target='chosen', amount=None, **k):
    return dict(trigger='onPlay', effect=effect, target=target, **({'amount': amount} if amount is not None else {}), **k)


def A(effect, target=None, amount=None, cost=None, **k):
    d = dict(trigger='activated', effect=effect, cost=cost or {}, **k)
    if target:
        d['target'] = target
    if amount is not None:
        d['amount'] = amount
    return d


def ST(scope, **k):
    return dict(trigger='static', scope=scope, **k)


def T(trigger, effect, target=None, amount=None, **k):
    d = dict(trigger=trigger, effect=effect, **k)
    if target:
        d['target'] = target
    if amount is not None:
        d['amount'] = amount
    return d


def todo(text):
    return {'todo': text}


def ether(n, **k):
    return dict(ether=n, **k)


def race(r):
    return {'race': r}


def cr(name, race_, text='', ab=(), kw=(), **x):
    return dict(name=name, race=race_, text=text, ab=list(ab), kw=list(kw), **x)


def so(name, text, ab=(), **x):
    return dict(name=name, text=text, ab=list(ab), **x)


def en(name, text, ab=(), attach='creature', **x):
    if attach == 'creature' and 'target' not in x:
        x['target'] = 'creature'
    return dict(name=name, text=text, ab=list(ab), attach=attach, **x)


