def card_prompt(c, tribes):
    fac = c.get('faction', 'neutral')
    parts = [STYLE, FACTION_STYLE.get(fac, FACTION_STYLE['neutral'])]
    if c['type'] == 'creature':
        look = (WALL_BY_ID.get(c['id']) or WALL_LOOK.get(fac)) if c.get('race') == 'wall' else TRIBE_LOOK.get(c.get('race'), '')
        cues = [KEYWORD_CUE[k.split(':')[0]] for k in c.get('keywords', []) if k.split(':')[0] in KEYWORD_CUE]
        size = 'огромный, занимает почти весь кадр' if c['cost'] >= 7 else ('крупный' if c['cost'] >= 4 else 'небольшой')
        subject = 'Сюжет: существо "%s" - %s, %s' % (c['name'], look, size)
        if cues:
            subject += ', ' + ', '.join(cues)
        if c.get('race') == 'wall':
            parts.append(subject + '. Кадр: укрепление в перспективе на фоне местности поля боя.')
        else:
            parts.append(subject + '. Кадр: существо в движении и в своём окружении (бежит, атакует, парит), '
                         'а не позирует; голова и главный силуэт в центре кадра, фон - местность фракции.')
    else:
        scene = SPELL_SCENE.get(c['id']) or 'визуальный образ эффекта "%s": %s' % (c['name'], c['text'])
        kind = 'заклинание' if c['type'] == 'sorcery' else 'чары'
        parts.append('Сюжет (%s "%s"): %s.' % (kind, c['name'], scene))
        if c['type'] == 'sorcery':
            parts.append('Кадр: сам момент эффекта крупно (вспышка, волна, разлом), фигуры - не больше одной и на втором плане.')
        else:
            parts.append('Кадр: предмет, аура или светящийся символ крупно в центре, почти абстрактная композиция.')
    parts.append(backdrop(fac))
    parts.append('Освещение: %s.' % ELEMENT_LIGHT.get(c['element'], ''))
    parts.append('Формат вертикальный 3:4. Одно изображение, без коллажа, панелей и нескольких вариантов на одном листе.')
    return ' '.join(parts)


def main():
    cards = {c['id']: c for c in json.load(open('data/cards.json', encoding='utf-8'))}
    races = json.load(open('data/races.json', encoding='utf-8'))
    monsters = json.load(open('data/monsters.json', encoding='utf-8'))
    campaign = json.load(open('data/campaign.json', encoding='utf-8'))
    tribes = json.load(open('data/tribes.json', encoding='utf-8'))
    concept = json.load(open('concept/four_factions_design_ru.json', encoding='utf-8'))
    leader_prompt = {f['id']: f['leader']['portrait_prompt'] for f in concept['factions']}
    leader_prompt['frontier_union'] = ('Оригинальный маршал пограничной колонии: обветренное суровое лицо со шрамом и щетиной, '
                                       'открытый шлем, тяжёлый силовой бронекостюм с массивными наплечниками, потёртой '
                                       'графитовой сталью, синими индикаторами и охристыми маркировками, за спиной дым и прожекторы.')

    items, seen = [], set()

    def add(batch, file_id, title, prompt, out):
        if file_id in seen:
            return
        seen.add(file_id)
        items.append({'batch': batch, 'file': file_id + '.png', 'title': title, 'out': out, 'prompt': prompt})

    def leader(batch, fac):
        fid, name = LEADERS[fac]
        add(batch, fid, 'Лидер: ' + name, STYLE + ' ' + FACTION_STYLE[fac] + ' Портрет: ' + leader_prompt[fac] + ' ' +
            backdrop(fac) + ' Формат квадратный 1:1, крупный план: голова и плечи. Одно изображение, без коллажа и панелей.',
            'heroes/' + fac)

    def field(batch, fac):
        add(batch, 'bg_' + fac, 'Фон поля боя: ' + FACTION_STYLE[fac].split('"')[1],
            STYLE.replace('Один главный объект в центре, не больше двух второстепенных элементов, важные детали не касаются краёв. ', '') +
            ' ' + FACTION_STYLE[fac] + ' Сюжет: пейзаж без персонажей - ' + FACTION_BACKDROP[fac] +
            '. Кадр: широкая панорама, центр картинки спокойный и тёмный (там лежат карты), детали и свет - по краям. '
            'Формат горизонтальный 16:9. Одно изображение, без коллажа и панелей.', 'backgrounds/' + fac)

    # Пачка 1: Пограничный Союз целиком и карты глав
    leader(1, FIRST)
    field(1, FIRST)
    for i, ch in enumerate(campaign['chapters']):
        add(1, 'map_%d' % (i + 1), 'Карта главы %d: %s' % (i + 1, ch['name']),
            STYLE.replace('Один главный объект в центре, не больше двух второстепенных элементов, важные детали не касаются краёв. ', '') +
            ' Сюжет: вид сверху под углом на местность без персонажей - ' + MAP_SCENE[i] +
            '. Кадр: широкая панорама, по середине тянется тропа, местность тёмная и спокойная (на ней лежат значки узлов), '
            'свет и детали - по краям. Формат горизонтальный 3:2. Одно изображение, без коллажа и панелей, без надписей.',
            'maps/ch%d' % (i + 1))
    starter = [r for r in races.values() if r['faction'] == FIRST][0]['starter']
    for c in sorted((c for c in cards.values() if c.get('faction') == FIRST and not c.get('special')),
                    key=lambda c: (c['id'] not in starter, c['cost'])):
        add(1, c['id'], c['name'], card_prompt(c, tribes), c['art'])
    # Пачка 2: остальные лидеры, фоны и стартовые колоды
    for fac in LEADERS:
        leader(2, fac)
    for fac in FACTION_BACKDROP:
        field(2, fac)
    for r in races.values():
        for cid in dict.fromkeys(r['starter']):
            c = cards[cid]
            add(2, cid, c['name'], card_prompt(c, tribes), c['art'])
    # Пачка 3: аватары монстров кампании
    for ch in campaign['chapters']:
        for n in ch['nodes']:
            if n.get('monster'):
                c = cards.get(monsters[n['monster']]['avatar'])
                if c:
                    add(3, c['id'], c['name'] + ' (монстр кампании)', card_prompt(c, tribes), c['art'])
    # Пачка 4: остальные карты фракций, пачка 5: Иные и служебные
    for c in cards.values():
        add(5 if c.get('special') else 4, c['id'], c['name'], card_prompt(c, tribes), c['art'])

    os.makedirs('art_inbox', exist_ok=True)
    with open('art_inbox/prompts.json', 'w', encoding='utf-8') as f:
        json.dump(items, f, ensure_ascii=False, indent=1)
    names = {1: 'Пачка 1: Пограничный Союз целиком', 2: 'Пачка 2: остальные лидеры, фоны и стартовые колоды',
             3: 'Пачка 3: монстры кампании', 4: 'Пачка 4: остальные карты фракций', 5: 'Пачка 5: Иные и служебные карты'}
    lines = ['# Описания для генерации картинок', '',
             'Как пользоваться: открой gemini.google.com, напиши "Нарисуй картинку:" и вставь описание целиком.',
             'Сохрани картинку в эту папку (art_inbox/) под именем из заголовка, например `ash_rat.png`.',
             'Если результат не нравится - попроси "Ещё вариант". Потом скажи мне, и я подключу картинки к игре.', '']
    for b in (1, 2, 3, 4, 5):
        group = [x for x in items if x['batch'] == b]
        lines += ['## %s (%d)' % (names[b], len(group)), '']
        for i, x in enumerate(group, 1):
            lines += ['### %d. `%s` - %s' % (i, x['file'], x['title']), '', x['prompt'], '']
    with open('art_inbox/ПРОМПТЫ.md', 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    for b in (1, 2, 3, 4, 5):
        print('%s: %d' % (names[b], sum(1 for x in items if x['batch'] == b)))


if __name__ == '__main__':
    main()
